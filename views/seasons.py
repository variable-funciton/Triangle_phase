"""季節の変化（気温・昼の長さを sin で表す）

グラフと操作はブラウザ側で動かす（assets/seasons.html, assets/seasons_core.js）。
"""

import streamlit as st

from utils.widget import render

st.title('季節の変化（気温・昼の長さを sin で表す）')
st.markdown(
    r"""1 年の気温や昼の長さは、周期 1 年の sin のグラフで近似できます。実際の平年値（気象庁）に合うように $A,\ \alpha,\ \beta$ を自分で動かして、三角関数の式を作ってみよう。"""
)

render('seasons', height=970)

with st.expander("📖 解説"):
    st.markdown(
        r"""**気温の式**　月 $m$（1〜12）の平均気温を $T = A\sin\dfrac{2\pi}{12}(m - \alpha) + \beta$ で近似する。

- $\beta$：1 年の平均気温（中心線）
- $A$：振幅。（いちばん暑い月 − いちばん寒い月）÷ 2 くらい
- $\alpha$：平行移動。曲線が中心線を下から上へ横切る月。いちばん暑いのは $\alpha + 3$ 月（周期 12 の $\frac{1}{4}$ あと）

**「いちばん合う値」の求め方**　$T \approx \beta + a\sin\omega m + b\cos\omega m$（$\omega = \frac{2\pi}{12}$）とおいて $a, b$ を求め、
**三角関数の合成** $a\sin\omega m + b\cos\omega m = A\sin(\omega m - \omega\alpha)$ で $A$ と $\alpha$ にしている（最小二乗法）。

**昼の長さ**　地軸が傾いているため、昼の長さも 1 年周期で変化する。緯度が高いほど振幅が大きく、赤道では振幅 0（いつも約 12 時間）。

**気温のデータ**：気象庁の平年値（1991〜2020 年の平均）、札幌・東京・那覇の月平均気温。"""
    )

with st.expander("📝 練習問題"):
    st.markdown(
        r"""1. 「いちばん合う値」で、札幌・東京・那覇の振幅 $A$ を比べよ。どこがいちばん大きく、それはなぜか。
2. 気温がいちばん高いのが夏至（6 月下旬）でなく 7 月下旬〜8 月上旬になるのはなぜか。
3. 東京（北緯 35.7°）の昼の長さを $12 + A\sin\frac{2\pi}{365}(N - 81)$ と表すとき、$A$ はおよそいくつか（グラフで調べよう）。夏至の昼の長さは何時間か。"""
    )
    with st.popover("答え"):
        st.markdown(
            r"""1. 札幌 約 12.7℃、東京 約 10.4℃、那覇 約 6.0℃。北の地域ほど夏と冬の太陽の高さ・昼の長さの差が大きいので振幅が大きい（那覇は海に囲まれていることも影響）。
2. 太陽からの熱で地面や海が温まるのに時間がかかるため（グラフでは $\alpha$ が約 1 か月遅れる）。
3. $A \approx 2.4$ 時間。夏至は約 $12 + 2.4 = 14.4$ 時間（実際の日の出〜日の入りは屈折などで約 14 時間半）。"""
        )
