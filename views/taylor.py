import streamlit as st

from utils.widget import render

st.title("テイラー展開：多項式で sin x, cos x に近づける")
st.markdown(
    r"$\sin x$ や $\cos x$ を、$x = x_0$ のまわりで **多項式（$x$ の何乗かの和）** で近似します。"
    r"次数 $n$ を上げるほど、ぴったり重なる範囲が広がっていきます。$x_0$ を動かすと、近似の中心も動きます。"
)

render("taylor", height=1150)

with st.expander("📖 解説：どうやって多項式を決めるのか"):
    st.markdown(
        r"""
**ねらい**　$\sin x$ のような関数は、電卓やコンピュータの中では直接計算できない。
そこで、足し算とかけ算だけで計算できる **多項式** で近似する。

**まず $x_0 = 0$ で考える**

| 次数 | 近似 | そろえたもの |
|:--:|:--|:--|
| 0 次 | $\sin x \approx 0$ | $x = 0$ での **値**（$\sin 0 = 0$） |
| 1 次 | $\sin x \approx x$ | 値と **傾き**（原点での接線の傾きは 1） |
| 3 次 | $\sin x \approx x - \dfrac{x^3}{3!}$ | 値・傾き・**曲がり方** をさらにそろえる |
| 5 次 | $\sin x \approx x - \dfrac{x^3}{3!} + \dfrac{x^5}{5!}$ | もっとそろえる |

$3! = 3 \times 2 \times 1 = 6$、$5! = 120$ のように、$k!$（k の階乗）で割っていく。
$\sin x$ は原点に関して対称（奇関数）なので、$x$ の奇数乗だけが現れる。
$\cos x$ は $y$ 軸に関して対称（偶関数）なので、偶数乗だけが現れる：

$$\cos x \approx 1 - \frac{x^2}{2!} + \frac{x^4}{4!} - \frac{x^6}{6!} + \cdots$$

**$x_0$ を動かすと**　$x = x_0$ のまわりで同じことをする。$(x - x_0)$ の何乗かの和になり、係数は

$$\sin x_0,\ \ \cos x_0,\ \ -\frac{\sin x_0}{2!},\ \ -\frac{\cos x_0}{3!},\ \ \frac{\sin x_0}{4!},\ \cdots$$

と、$\sin \to \cos \to -\sin \to -\cos \to \sin$ のくり返しを $k!$ で割ったものになる
（「接線の傾きをグラフにすると？」のページで見た、$\sin$ の傾きが $\cos$、$\cos$ の傾きが $-\sin$ になることから来ている）。
"""
    )
    st.info(
        "微分を学ぶと、k 番目の係数は「k 回微分した値 ÷ k!」として説明できます。"
        "このように関数を多項式で表す方法をテイラー展開（x₀ = 0 のときはマクローリン展開）といいます。"
    )

with st.expander("📝 観察してみよう"):
    st.markdown(
        r"""
1. $x_0 = 0$、関数 sin x で、次数を 1, 3, 5, 7 と上げたとき、緑の範囲（誤差 0.01 未満）はどのくらい広がるか。
2. sin x、$x_0 = 0$ で、次数 3 と 4 のグラフが同じになるのはなぜか。
3. 電卓で $\sin 0.5$ を求め、$0.5 - \dfrac{0.5^3}{6}$ と比べよう。
4. $x_0$ を $\pi$ にすると、近似の式はどう変わるか。グラフはどう見えるか。
"""
    )
    with st.popover("答えの例"):
        st.markdown(
            r"""
1. 幅がだいたい 0.8 → 2.1 → 3.5 → 5.0 と広がる（次数を 2 上げるごとに 1.4 くらいずつ広がる）。
2. $\sin x$ の展開には $x$ の偶数乗の項がない（係数 $\sin 0 = 0$）ので、4 次の項を足しても変わらない。
3. $\sin 0.5 = 0.47942\cdots$、$0.5 - 0.020833\cdots = 0.47916\cdots$。小数第 3 位まで合う。
4. $\sin x \approx -(x - \pi) + \dfrac{(x-\pi)^3}{3!} - \cdots$。$x_0 = 0$ のグラフを右へ $\pi$ ずらし、上下を反転した形（$\sin x = -\sin(x - \pi)$）。
"""
        )
