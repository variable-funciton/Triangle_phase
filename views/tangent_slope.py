"""sin x のグラフの接線の傾きをプロットすると cos x が現れる（微分の入り口）

グラフと操作はブラウザ側で動かす（assets/tangent_slope.html, assets/tangent_slope_core.js）。
"""

import streamlit as st

from utils.widget import render

st.title("接線の傾きをグラフにすると？")
st.markdown(
    r"$y = \sin x$ のグラフの上を点 P が動くとき、P での **接線の傾き** $m$ を下のグラフに点 $(a, m)$ として"
    "たくさん打っていきます。点を集めると、どんなグラフが現れるでしょう？"
)

render("tangent_slope", height=1200)

with st.expander("📖 解説：接線の傾きとは（微分をまだ習っていなくても大丈夫）"):
    st.markdown(
        r"""
**傾き**　直線 $y = mx + n$ の $m$ は「右へ 1 進むと上へ $m$ 進む」という傾きの大きさ。
グラフの緑の三角形がこれを表している。

**接線**　曲線上の点 P で、曲線に「ふれるように」引いた直線。P のすぐ近くでは曲線と接線はほとんど重なって見える。
曲線の **その点での傾き** を、接線の傾きで表す。

**接線の傾きの求め方（割線から近づける）**　曲線上に P と、P から右へ $h$ だけ離れた点 Q をとる。
直線 PQ（割線）の傾きは

$$\frac{\sin(a+h) - \sin a}{h}$$

$h$ をどんどん小さくすると、Q が P に近づき、割線は接線に近づく。
「割線から近づける」にチェックを入れて、$h$ のスライダーを小さくしていこう。

**観察のポイント**

- 山の頂上 $x = \frac{\pi}{2}$ と谷の底 $x = \frac{3\pi}{2}$ では接線が水平なので $m = 0$。
- $x = 0$ では $m = 1$。原点の近くでは $\sin x$ のグラフは直線 $y = x$ とほとんど同じ（$\sin x \approx x$）。
- $x = \pi$ では $m = -1$（最も急に下っている）。
- この 3 つの特徴をもつのは……？　予想してから「答え合わせ」にチェックを入れよう。

**わかること**　$y = \sin x$ の接線の傾きを並べると $y = \cos x$ になる。
同じように $y = \cos x$ の接線の傾きを並べると $y = -\sin x$ になる（関数を cos x に切りかえて確かめよう）。
このように「各点での接線の傾き」を並べた関数を **導関数** といい、求めることを **微分する** という。
微分の授業で、$(\sin x)' = \cos x$、$(\cos x)' = -\sin x$ として学びます。
"""
    )
    st.info(
        "このページの傾きは公式を使わずに、とても小さい h（0.00001）で割線の傾きを計算して求めています。"
        "それでも cos x の値と小数第 6 位くらいまで一致します。"
    )

with st.expander("📝 考えてみよう"):
    st.markdown(
        r"""
1. $h = 1$ のときの割線の傾きを並べたグラフ（チェックを入れて ▶）は、$\cos x$ と比べてどうずれているか。
2. $y = \sin 2x$ の接線の傾きを並べると、どんなグラフになると予想できるか。（ヒント：グラフは x 方向に $\frac{1}{2}$ 倍に縮む。縮むと傾きは急になる）
3. $\sin x \approx x$（$x$ が 0 に近いとき）を、電卓で $x = 0.1,\ 0.01$ について確かめよう。
"""
    )
    with st.popover("答えの例"):
        st.markdown(
            r"""
1. 形は cos x とそっくりだが、少し左にずれて、山の高さも少し低い。$h$ を小さくするとずれがなくなる。
2. $y = 2\cos 2x$（周期が半分になり、傾きは 2 倍になる）
3. $\sin 0.1 = 0.0998\cdots$、$\sin 0.01 = 0.0099998\cdots$
"""
        )
