import streamlit as st

from utils.widget import render

st.title('日影と建物の間隔（太陽高度と tan）')
st.markdown(
    r"""太陽の高さ（太陽高度）$h$ と建物の高さ $H$ から、影の長さは $L = \dfrac{H}{\tan h}$。冬至・夏至の南中高度、北側の建物に日を当てるための間隔、1 日の影の動きを調べよう。"""
)

render('shadow', height=1000)

with st.expander("📖 解説"):
    st.markdown(
        r"""**南中高度**　太陽が真南にきたときの高さ。緯度 $\varphi$、太陽の赤緯 $\delta$（夏至 $+23.4^\circ$、春分・秋分 $0^\circ$、冬至 $-23.4^\circ$）として

$$h = 90^\circ - \varphi + \delta$$

東京（北緯 35.7°）では、夏至 約 77.7°、春分・秋分 約 54.3°、冬至 約 30.9°。

**影の長さ**　高さ $H$ の建物の影は $L = \dfrac{H}{\tan h}$。冬至の東京では $\tan 30.9^\circ \approx 0.60$ なので、影は高さの約 1.7 倍。

**建物の間隔**　北側の建物に南中時に日を当てるには、間隔 $D \ge \dfrac{H}{\tan h}$ が必要。
住宅地では、冬至の日に一定時間以上の日影ができないように建物の高さを制限する決まり（日影規制）があり、このような計算が使われている。

**1 日の影の動き**　時刻とともに太陽の方角と高さが変わり、棒の影の先端は曲線（日影曲線）をえがく。"""
    )

with st.expander("📝 練習問題"):
    st.markdown(
        r"""1. 東京（北緯 35.7°）の夏至の南中高度を求めよ。そのとき高さ 10 m の木の影の長さは何 m か。
2. 札幌（北緯 43.1°）の冬至の南中高度を求めよ。影は建物の高さの何倍か。
3. 東京で、高さ 20 m の建物の北側に、冬至の南中時に日が当たる建物を建てたい。何 m 以上はなせばよいか。"""
    )
    with st.popover("答え"):
        st.markdown(
            r"""1. $90 - 35.7 + 23.4 = 77.7^\circ$。$L = \frac{10}{\tan 77.7^\circ} \approx 2.2$ m
2. $90 - 43.1 - 23.4 = 23.5^\circ$。$\frac{1}{\tan 23.5^\circ} \approx 2.3$ 倍
3. $\frac{20}{\tan 30.9^\circ} \approx 33.5$ m 以上"""
        )
